// @ts-nocheck
// Design-token generator for Vautr ("The Vault Ledger").
// Zero runtime deps. Reads the authored sources and emits platform outputs:
//   dist/tokens.css        -> consumed by apps/extension + apps/web (globals.css @import)
//   dist/tokens.rs         -> consumed by apps/desktop/src/theme.rs (re-export)
//   dist/tokens.ts         -> consumed by mobile/lib (NativeWind theme)
//   dist/vautr-theme.json  -> GPUI-component theme (apps/desktop/src/vautr-theme.json)
//   dist/tokens.md         -> human-readable swatches (docs)
//
// Source of truth: ../tokens.json (primitives, dark+light) + ../gpui-map.json
// (primitive -> GPUI semantic key assignment). Never hand-edit the dist/ files.
//
// Usage: node scripts/build.mjs            (write outputs)
//        node scripts/build.mjs --check    (assert outputs already match; CI gate)

import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Collapse all whitespace runs so formatter drift (cargo fmt / css reflow)
 *  does not cause a false token-drift failure. Token-value edits still differ. */
function normalizeWs(s) {
  return s.replace(/\s+/g, ' ').trim();
}

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

const CHECK = process.argv.includes('--check');

const tokens = JSON.parse(readFileSync(join(ROOT, 'tokens.json'), 'utf8'));
const gpuiMap = JSON.parse(readFileSync(join(ROOT, 'gpui-map.json'), 'utf8'));

// --- resolve {group.name} references against tokens.json ---
function ref(path) {
  const [group, name] = path.replace(/[{}]/g, '').split('.');
  const node = tokens[group]?.[name];
  if (!node) throw new Error(`Unresolved token ref: ${path}`);
  return node;
}
function modeHex(node, mode) {
  const v = node.$value;
  if (typeof v === 'string') return v; // literal (e.g. scrollbar hex8)
  return v[mode];
}
function _isColor(group) {
  return group === 'color';
}

// --- CSS ---
// Explicit map: token path -> shadcn CSS var name used across web/extension
// (must match the names components already reference, so globals.css can drop
// its hand-typed block without touching any component).
